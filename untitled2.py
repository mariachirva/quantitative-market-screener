def run_strategy_5(ticker, tf_input):
    print("\n>>> STRATEGIE 5: Markov Stationary")
    try:
        close = get_historical_data_for_tf(ticker, tf_input)
        if close.empty or len(close) < 100: return 0, "No Data"

        ret = np.log(close/close.shift(1)).dropna()
        z = (ret - ret.rolling(100).mean()) / ret.rolling(100).std()
        states = np.select([(z>0.4), (z<-0.4)], [1, 2], default=0)

        counts = np.zeros((3,3))
        for i in range(1, len(states)): counts[states[i-1]][states[i]] += 1
        P = counts / (counts.sum(axis=1, keepdims=True) + 1e-6)
        steady = np.linalg.matrix_power(P, 20)[0]

        print(f"   Steady State ({tf_input}): Bull {steady[1]:.2f} | Bear {steady[2]:.2f} | Neutral {steady[0]:.2f}")

        prob_next_bull = P[states[-1], 1]
        prob_next_bear = P[states[-1], 2]

        score = 0
        if prob_next_bull > 0.35 and prob_next_bull > prob_next_bear: score += 1
        elif prob_next_bear > 0.35 and prob_next_bear > prob_next_bull: score -= 1

        if steady[1] > steady[2]: score += 1
        elif steady[2] > steady[1]: score -= 1

        if score >= 1: return 1, "Long"
        if score <= -1: return -1, "Short"
        return 0, "Neutral"
    except Exception as e:
        print(f"Err S5: {e}")
        return 0, "Error"

