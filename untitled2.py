class MarkovForecaster:
    def __init__(self, ticker, tf_input):
        self.ticker = ticker
        self.tf = tf_input
        self.data = None; self.returns = None; self.states = None; self.P = None
        self.mu = None; self.sigma = None; self.global_mu = 0

    def run(self):
        try:
            self.data = get_historical_data_for_tf(self.ticker, self.tf)
            if self.data.empty or len(self.data) < 50:
                print("   Zu wenig Daten für Markov.")
                return 0

            self.returns = np.log(self.data / self.data.shift(1)).dropna()
            self.global_mu = self.returns.mean()

            z = zscore(self.returns)
            self.states = np.select([(z > 0.5), (z < -0.5)], [1, 2], default=0)

            n=3; P=np.zeros((n,n))
            for (i,j) in zip(self.states[:-1], self.states[1:]): P[i,j]+=1
            row_s = P.sum(axis=1, keepdims=True); row_s[row_s==0]=1; self.P = P/row_s

            sims=1000; steps=21; paths=np.zeros((sims,steps))
            curr = self.data.iloc[-1]; last_s = self.states[-1]
            df_s = pd.DataFrame({'r': self.returns, 's': self.states})
            g = df_s.groupby('s')['r'].agg(['mean','std']).to_dict('index')

            for i in range(sims):
                p = curr; s = last_s
                for d in range(steps):
                    if np.sum(self.P[s])==0: s=0
                    else: s = np.random.choice([0,1,2], p=self.P[s])

                    # Werte abrufen
                    mu = g.get(s, {}).get('mean', 0)
                    sig = g.get(s, {}).get('std', 0.01)

                    # NaN-Check (verhindert das +nan% Problem)
                    if pd.isna(mu): mu = 0.0
                    if pd.isna(sig) or sig == 0.0: sig = 0.01

                    p *= np.exp(np.random.normal(mu, sig))
                paths[i,:] = p

            bull_prob = np.mean(paths[:,-1] > curr)
            trend = (np.mean(paths[:,-1]) - curr)/curr * 100

            print(f"   Bull Prob: {bull_prob:.1%} | Exp. Return: {trend:+.2f}% (auf {self.tf} Basis)")
            if trend > 0.2 and bull_prob > 0.55: return 1
            elif trend < -0.2 and bull_prob < 0.45: return -1
            return 0
        except Exception as e:
            print(f"Err S4: {e}")
            return 0

