def calculate_risk_flags(series, name):
    delta = series.diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
    rs = gain / loss
    rsi = 100 - (100 / (1 + rs))
    curr_rsi = rsi.iloc[-1]

    sma20 = series.rolling(window=20).mean()
    std20 = series.rolling(window=20).std()
    pb = (series.iloc[-1] - (sma20 - 2*std20)) / (4 * std20)
    curr_pb = pb.iloc[-1]

    sma50 = series.rolling(window=50).mean()
    dist_sma50 = (series.iloc[-1] - sma50.iloc[-1]) / sma50.iloc[-1] * 100

    curr_std = std20.iloc[-1]
    curr_sma50 = sma50.iloc[-1]
    adaptive_limit = (3.0 * curr_std / curr_sma50) * 100
    if adaptive_limit < 3.0: adaptive_limit = 3.0

    rsi_mark = "✅"
    if curr_rsi > 75: rsi_mark = "⚠️ >75 (High)"
    elif curr_rsi < 25: rsi_mark = "⚠️ <25 (Low)"

    pb_mark = "✅"
    if curr_pb > 1.0: pb_mark = "⚠️ >1.0 (High)"
    elif curr_pb < 0.0: pb_mark = "⚠️ <0.0 (Low)"

    dist_mark = "✅"
    if dist_sma50 > adaptive_limit: dist_mark = f"⚠️ >{adaptive_limit:.1f}% (Vol-Adj)"
    elif dist_sma50 < -adaptive_limit: dist_mark = f"⚠️ <-{adaptive_limit:.1f}% (Vol-Adj)"

    print(f"   1. RSI (14) [{name}]:     {curr_rsi:.2f}  {rsi_mark}")
    print(f"   2. Boll %B  [{name}]:     {curr_pb:.2f}   {pb_mark}")
    print(f"   3. Dist SMA50 [{name}]:   {dist_sma50:.1f}%  {dist_mark}")
    print(f"      (Adaptive Limit: +/- {adaptive_limit:.1f}%)")

    w_long = 0
    if curr_rsi > 75: w_long += 1
    if curr_pb > 1.0: w_long += 1
    if dist_sma50 > adaptive_limit: w_long += 1

    w_short = 0
    if curr_rsi < 25: w_short += 1
    if curr_pb < 0.0: w_short += 1
    if dist_sma50 < -adaptive_limit: w_short += 1

    return w_long, w_short

