def check_relative_volume(ticker):
    try:
        df = yf.download(ticker, period="3mo", interval="1d", progress=False, auto_adjust=True)
        if df.empty: return 0.0, 0, 0

        if isinstance(df.columns, pd.MultiIndex):
            vol = df.xs('Volume', axis=1, level=0).iloc[:, 0]
        else:
            vol = df['Volume']

        vol = vol.dropna()
        if len(vol) < 22: return 0.0, 0, 0

        last_date = vol.index[-1].date()
        today = datetime.now().date()

        if last_date == today:
            vol_yesterday = vol.iloc[-2]
            vol_avg_20 = vol.iloc[-22:-2].mean()
        else:
            vol_yesterday = vol.iloc[-1]
            vol_avg_20 = vol.iloc[-21:-1].mean()

        if vol_avg_20 == 0: return 0.0, vol_yesterday, 0

        rel_vol = vol_yesterday / vol_avg_20
        return rel_vol, vol_yesterday, vol_avg_20

    except Exception as e:
        return 0.0, 0, 0

