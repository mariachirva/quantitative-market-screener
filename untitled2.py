def check_trend_quality(ticker, tf_input):
    macro_slope = 0; macro_r2 = 0; macro_er = 0
    micro_slope = 0; micro_r2 = 0; micro_er = 0

    try:
        df = yf.download(ticker, period="6mo", progress=False)
        if not df.empty:
            if isinstance(df.columns, pd.MultiIndex): closes = df.xs('Close', axis=1, level=0).iloc[:, 0]
            else: closes = df['Close']
            closes = closes.dropna().tail(90)

            if len(closes) >= 30:
                y = np.log(closes.values)
                x = np.arange(len(y))
                slope, intercept, r_value, p_value, std_err = linregress(x, y)
                macro_slope = slope * 100
                macro_r2 = r_value**2

                change = abs(closes.iloc[-1] - closes.iloc[0])
                volatility = closes.diff().abs().sum()
                macro_er = change / volatility if volatility != 0 else 0
    except: pass

    try:
        micro_interval = "1h"
        micro_period = "1mo"
        resample_rule = None

        if tf_input == '1H':
            micro_interval = "15m"
            micro_period = "1mo"
        elif tf_input == '2H':
            micro_interval = "30m"
            micro_period = "1mo"
        elif tf_input == '4H':
            micro_interval = "1h"
            micro_period = "6mo"
        elif tf_input == '1D':
            micro_interval = "1h"
            micro_period = "6mo"
            resample_rule = "4h"

        df_micro = yf.download(ticker, period=micro_period, interval=micro_interval, progress=False)

        if not df_micro.empty:
            if isinstance(df_micro.columns, pd.MultiIndex):
                m_closes = df_micro.xs('Close', axis=1, level=0).iloc[:, 0]
            else:
                m_closes = df_micro['Close']

            if resample_rule:
                m_closes = m_closes.resample(resample_rule).last().dropna()

            m_closes = m_closes.tail(50)

            if len(m_closes) > 10:
                y_mic = np.log(m_closes.values)
                x_mic = np.arange(len(y_mic))
                slope_mic, _, r_val_mic, _, _ = linregress(x_mic, y_mic)
                micro_slope = slope_mic * 100
                micro_r2 = r_val_mic**2

                change_mic = abs(m_closes.iloc[-1] - m_closes.iloc[0])
                vol_mic = m_closes.diff().abs().sum()
                micro_er = change_mic / vol_mic if vol_mic != 0 else 0

    except Exception as e:
        pass

    return macro_slope, micro_slope, macro_r2, macro_er, micro_r2, micro_er

