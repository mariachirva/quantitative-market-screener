def black_scholes_call_price(S, K, T, r, sigma):
    if T <= 0 or sigma <= 0: return np.maximum(S - K, 0)
    d1 = (np.log(S / K) + (r + 0.5 * sigma ** 2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return (S * norm.cdf(d1)) - (K * np.exp(-r * T) * norm.cdf(d2))

def get_clean_option_data(ticker, date, current_price):
    try:
        tk = yf.Ticker(ticker)
        opts = tk.option_chain(date)
        calls, puts = opts.calls, opts.puts
    except Exception: return pd.DataFrame()

    if calls.empty or puts.empty: return pd.DataFrame()
    otm_puts = puts[puts['strike'] < current_price].copy()
    otm_calls = calls[calls['strike'] >= current_price].copy()
    df = pd.concat([otm_puts, otm_calls])
    df = df.dropna(subset=['impliedVolatility'])
    df = df[(df['impliedVolatility'] > 0.01) & (df['impliedVolatility'] < 4.0)]
    df = df[['strike', 'impliedVolatility']].sort_values('strike')
    return df

